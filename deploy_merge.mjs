// deploy_merge.mjs — copy the PDF Merge Tool into merge/ for the "Merge PDFs"
// card button. The merge tool itself stays the single source of truth
// (PDF Merge Tool/PDF_merge_tool.html); merge/ is a generated deploy copy —
// never edit it by hand. Its Trello behaviour lives in the tool's own
// "Trello mode" block, which only activates at merge/?trello=1 inside Trello.
//
// Changes made to the copy:
//   * pdf.js workerSrc -> the same-origin vendored worker (a cross-origin
//     workerSrc silently drops pdf.js to its slow main-thread fake worker)
//   * font_data.js keeps ONLY the open Liberation fallback fonts — the
//     licensed Swiss 721 TTFs are never published. Unembedded Swiss text in
//     source drawings gets Liberation Sans/Narrow instead.
//
// Run: node deploy_merge.mjs   (auto_push_core.ps1 runs it before committing)
// Output is deterministic, so git only sees a change when the tool changed.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "PDF Merge Tool");
const out = join(here, "merge");
mkdirSync(out, { recursive: true });

// 1. The tool page
const CDN_WORKER = 'pdfjsLib.GlobalWorkerOptions.workerSrc="https://cdnjs.cloudflare.com/ajax/libs/pdf.js/3.11.174/pdf.worker.min.js"';
const LOCAL_WORKER = 'pdfjsLib.GlobalWorkerOptions.workerSrc=new URL("../js/vendor/pdf.worker.min.js",location.href).href';
let html = readFileSync(join(src, "PDF_merge_tool.html"), "utf8");
if (!html.includes(CDN_WORKER)) throw new Error("workerSrc line not found — update deploy_merge.mjs");
if (!html.includes("function trelloMode()")) throw new Error("Trello mode block missing from the merge tool");
html = html.replace(CDN_WORKER, LOCAL_WORKER);
writeFileSync(join(out, "index.html"), html);

// 2. Templates, unchanged
writeFileSync(join(out, "tpl_data.js"), readFileSync(join(src, "tpl_data.js")));

// 3. Fonts: open fallbacks only
const fontSrc = join(src, "font_data.js");
if (existsSync(fontSrc)) {
  const FONT_DATA = new Function(readFileSync(fontSrc, "utf8") + "\nreturn FONT_DATA;")();
  const keys = Object.keys(FONT_DATA.fallback || {}).sort();
  if (!keys.length) throw new Error("font_data.js has no fallback fonts");
  const lines = keys.map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(FONT_DATA.fallback[k])}`);
  writeFileSync(join(out, "font_data.js"),
    "// GENERATED by deploy_merge.mjs — open Liberation fonts only (no Swiss 721).\n" +
    "const FONT_DATA = {\n  exact: {},\n  fallback: {\n" + lines.join(",\n") + "\n  }\n};\n");
}

console.log("merge/ updated: index.html, tpl_data.js" + (existsSync(fontSrc) ? ", font_data.js (open fonts only)" : ""));
